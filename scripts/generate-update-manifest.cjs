'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const pkg=require('../package.json');const tag=process.env.RELEASE_TAG||'';
if(tag!==`v${pkg.version}`||!/\d+\.\d+\.\d+/.test(pkg.version))throw Error('Release tag must exactly match package version');
const name=`Frame_Builder_${pkg.version}_Windows_x64.exe`;
const dest=path.resolve(__dirname,'../dist',name);
if(!fs.existsSync(dest))throw Error('Windows portable EXE missing: '+dest);
const bytes=fs.readFileSync(dest);
if(bytes.length<1_000_000)throw Error('Unexpected small executable');
const url=`https://github.com/TechSavage1989/Frame-Builder/releases/download/${tag}/${name}`;
const releaseNotes=fs.readFileSync(path.resolve(__dirname,'../docs/releases/RELEASE_NOTES.md'),'utf8');
if(releaseNotes.split(/\r?\n/,1)[0]!=='# Frame Builder '+pkg.version)throw Error('Release notes must match package version');
const bullets=releaseNotes.split(/\r?\n/).filter(line=>line.startsWith('- ')).map(line=>line.slice(2).trim()).filter(Boolean);
if(!bullets.length)throw Error('Release notes need at least one summary bullet');
const notes=bullets.slice(0,3).map(note=>note.length>180?note.slice(0,177).replace(/\s+\S*$/,'')+'...':note);
const manifest={appId:'com.techsavage3d.canvasframe',product:'Frame Builder',version:pkg.version,asset:{name,kind:'windows-portable-exe',url,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),size:bytes.length},notes,hasMoreNotes:true,readMore:`https://github.com/TechSavage1989/Frame-Builder/releases/tag/${tag}`};
fs.writeFileSync(path.join(path.dirname(dest),'update-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
fs.writeFileSync(path.join(path.dirname(dest),'SHA256SUMS.txt'),manifest.asset.sha256+'  '+name+'\n');
console.log('Release manifest: '+name+' '+manifest.asset.sha256);
